  function pickLine(list, branch) {
    return (list || []).filter(function (item) {
      if (!item.when) return true;
      var w = Array.isArray(item.when) ? item.when : [item.when];
      return w.indexOf(branch) >= 0;
    }).map(function (item) {
      var copy = {};
      for (var k in item) {
        if (Object.prototype.hasOwnProperty.call(item, k)) copy[k] = item[k];
      }
      delete copy.when;
      return copy;
    });
  }

